-- WHERE, BETWEEN, ORDER BY
SELECT *
FROM Worker
WHERE DEPARTMENT = 'HR';

SELECT FIRST_NAME, LAST_NAME, SALARY
FROM Worker
WHERE SALARY > 100000;

SELECT *
FROM Worker
WHERE DEPARTMENT IN ('Admin', 'Account');

SELECT *
FROM Worker
WHERE SALARY BETWEEN 75000 AND 300000;

SELECT *
FROM Worker
ORDER BY SALARY ASC;

SELECT *
FROM Worker
ORDER BY JOINING_DATE DESC;

SELECT *
FROM Worker
ORDER BY DEPARTMENT ASC, SALARY DESC;

-- Aggregate Functions and GROUP BY
SELECT DEPARTMENT, COUNT(*) AS TOTAL_EMPLOYEES
FROM Worker
GROUP BY DEPARTMENT;

SELECT DEPARTMENT, AVG(SALARY) AS AVERAGE_SALARY
FROM Worker
GROUP BY DEPARTMENT;

SELECT DEPARTMENT, MAX(SALARY) AS MAX_SALARY
FROM Worker
GROUP BY DEPARTMENT;

SELECT DEPARTMENT, COUNT(*) AS TOTAL_EMPLOYEES
FROM Worker
GROUP BY DEPARTMENT
HAVING COUNT(*) > 2;

-- Subqueries
SELECT *
FROM Worker
WHERE SALARY > (
    SELECT AVG(SALARY)
    FROM Worker
);

SELECT *
FROM Worker
WHERE DEPARTMENT = (
    SELECT DEPARTMENT
    FROM Worker
    WHERE FIRST_NAME = 'Monika'
);

SELECT *
FROM Worker

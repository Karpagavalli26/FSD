-- Group  By

SELECT DEPARTMENT, SUM(SALARY) AS TOTAL_SALARY
FROM Worker
GROUP BY DEPARTMENT
ORDER BY TOTAL_SALARY DESC;

SELECT DEPARTMENT, AVG(SALARY) AS AVERAGE_SALARY
FROM Worker
GROUP BY DEPARTMENT
ORDER BY AVERAGE_SALARY ASC;

SELECT DEPARTMENT, COUNT(*) AS WORKER_COUNT
FROM Worker
GROUP BY DEPARTMENT
ORDER BY WORKER_COUNT DESC;

SELECT DEPARTMENT, MIN(SALARY) AS MINIMUM_SALARY
FROM Worker
GROUP BY DEPARTMENT
ORDER BY MINIMUM_SALARY ASC;
 
 -- Combine of multiple functions

SELECT DEPARTMENT,
COUNT(*) AS TOTAL_WORKERS,
MAX(SALARY) AS MAXIMUM_SALARY,
MIN(SALARY) AS MINIMUM_SALARY
FROM Worker
GROUP BY DEPARTMENT;

SELECT DEPARTMENT,
SUM(SALARY) AS TOTAL_SALARY,
AVG(SALARY) AS AVERAGE_SALARY
FROM Worker
GROUP BY DEPARTMENT;

SELECT DEPARTMENT,
COUNT(*) AS TOTAL_WORKERS,
AVG(SALARY) AS AVERAGE_SALARY
FROM Worker
GROUP BY DEPARTMENT
ORDER BY AVERAGE_SALARY DESC;

SELECT DEPARTMENT,
MAX(SALARY) AS HIGHEST_SALARY,
MIN(SALARY) AS LOWEST_SALARY
FROM Worker
GROUP BY DEPARTMENT
ORDER BY HIGHEST_SALARY DESC;

-- Having
SELECT department, COUNT(first_name)
FROM Worker
GROUP BY department
HAVING COUNT(first_name) > 2
ORDER BY COUNT(first_name) ASC;

